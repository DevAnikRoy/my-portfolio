export function webflowPreviewPath(live) {
  try {
    const host = new URL(live).hostname
      .replace(/^www\./i, "")
      .replace(/\.webflow\.io$/i, "");
    return `/webflow-previews/${host}.jpg`;
  } catch {
    return "";
  }
}

